const FALLBACK_COLORS: [u32; 8] = [
    0x74c0fc, 0xb197fc, 0x63e6be, 0xffd43b, 0xff8787, 0xf783ac, 0xffa94d, 0x8ce99a,
];

pub fn language_color(language: &str) -> u32 {
    let color = linguist_color(language).unwrap_or_else(|| {
        let hash = language.bytes().fold(0usize, |hash, byte| {
            hash.wrapping_mul(31).wrapping_add(byte as usize)
        });
        FALLBACK_COLORS[hash % FALLBACK_COLORS.len()]
    });

    readable(color)
}

/// Lightens colors that would disappear against the dark card background.
fn readable(color: u32) -> u32 {
    let [_, r, g, b] = color.to_be_bytes();
    let luminance = (0.2126 * r as f32 + 0.7152 * g as f32 + 0.0722 * b as f32) / 255.0;
    if luminance >= 0.3 || r.max(g).max(b) >= 180 {
        return color;
    }

    let lighten = |channel: u8| channel + (255 - channel) / 2;
    u32::from_be_bytes([0, lighten(r), lighten(g), lighten(b)])
}

